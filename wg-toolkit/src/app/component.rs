//! Typed bindings to the dynamic components of a loaded script, which entities in a
//! space carry and clients get over NRL (see the `Nrl*` elements of
//! [`super::client::element`]).
//!
//! A schema declares, with [`component_schema!`], the members of a component type that a
//! server uses, as [`super::entity`]'s schemas do: client methods it calls and properties
//! it sets. A component is added to an entity with [`Entity::add_component`], given who
//! gets it. The app numbers its NRL nodes: the clients knowing the entity get it at the
//! end of the tick, with every property it was given a value, then what changes of it,
//! each tick.
//!
//! [`Entity::add_component`]: super::entity::Entity::add_component

