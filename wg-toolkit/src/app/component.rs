/// A property a component schema declares, with its type.
pub struct ComponentPropertyDecl {
    pub name: &'static str,
    pub ty: TypeDecl,
}

/// The members of a dynamic component type that a server uses, a subset of the
/// script's, implemented by [`component_schema!`]. Its [`Component`] views deref to
/// [`Self::View`].
pub trait ComponentSchema: 'static {
    /// The component type's name in the script.
    const NAME: &'static str;
    /// The client methods it calls.
    const CLIENT_METHODS: &'static [MethodDecl];
    /// The properties it sets.
    const PROPERTIES: &'static [ComponentPropertyDecl];
    type View<'a>: ComponentView<'a>;
}

/// The view a [`Component`] derefs to, generated by [`component_schema!`] with a method
/// per declared member.
pub trait ComponentView<'a> {
    fn new(raw: RawComponent<'a>) -> Self;
    fn raw(&self) -> &RawComponent<'a>;
    fn raw_mut(&mut self) -> &mut RawComponent<'a>;
}

/// A component schema bound to a component type of the loaded script, see [`bind`].
#[derive(Debug)]
pub struct ComponentBound {
    schema: TypeId,
    /// The index of each declared client method and property in its table.
    client_methods: Vec<u16>,
    properties: Vec<u16>,
}

impl ComponentBound {

    /// Whether this is the given schema's binding.
    pub fn is<C: ComponentSchema>(&self) -> bool {
        self.schema == TypeId::of::<C>()
    }

}

/// Bind a component schema to its component type's tables, checking each declared
/// member.
pub fn bind<C: ComponentSchema>(dispatch: &EntityDispatch) -> Result<ComponentBound, BindError> {

    let mut errors = Vec::new();

    let client_methods = C::CLIENT_METHODS.iter().filter_map(|decl| {
        let Some(index) = dispatch.client_methods.iter().position(|def| &*def.name == decl.name) else {
            errors.push(format!("no client method {}", decl.name));
            return None;
        };
        let def = &dispatch.client_methods[index];
        if def.args.len() != decl.args.len() {
            errors.push(format!("client method {} takes {} arguments, not {}", decl.name, def.args.len(), decl.args.len()));
        }
        for (i, (ty, arg)) in def.args.iter().zip(decl.args).enumerate() {
            if !(arg.check)(ty) {
                errors.push(format!("client method {} argument {i} is a {}, not a {}", decl.name, describe(ty), (arg.name)()));
            }
        }
        Some(index as u16)
    }).collect();

    let properties = C::PROPERTIES.iter().filter_map(|decl| {
        let Some(index) = dispatch.properties.iter().position(|def| &*def.name == decl.name) else {
            errors.push(format!("no property {}", decl.name));
            return None;
        };
        let def = &dispatch.properties[index];
        if !(decl.ty.check)(&def.ty) {
            errors.push(format!("property {} is a {}, not a {}", decl.name, describe(&def.ty), (decl.ty.name)()));
        }
        Some(index as u16)
    }).collect();

    if errors.is_empty() {
        Ok(ComponentBound { schema: TypeId::of::<C>(), client_methods, properties })
    } else {
        Err(BindError { schema: C::NAME, errors })
    }

}

/// The component schemas registered with an app, by component type id.
#[derive(Debug, Default)]
pub(crate) struct ComponentRegistry {
    bindings: HashMap<u16, ComponentBound>,
    schema_types: HashMap<TypeId, u16>,
}

impl ComponentRegistry {

    /// Bind a schema to its component type, see [`bind`].
    pub fn register<C: ComponentSchema>(&mut self, script: &ScriptDispatch) -> Result<(), BindError> {
        let Some((type_id, dispatch)) = script.entity_from_name(C::NAME) else {
            return Err(BindError { schema: C::NAME, errors: vec![format!("no component type {}", C::NAME)] });
        };
        if script.component_nrl_id(type_id).is_none() {
            return Err(BindError { schema: C::NAME, errors: vec!["the client has no class for it".to_string()] });
        }
        self.bindings.insert(type_id, bind::<C>(dispatch)?);
        self.schema_types.insert(TypeId::of::<C>(), type_id);
        Ok(())
    }

    /// The component type of a registered schema, and its binding.
    fn of<C: ComponentSchema>(&self) -> io::Result<(u16, &ComponentBound)> {
        let type_id = *self.schema_types.get(&TypeId::of::<C>())
            .ok_or_else(|| invalid(format!("component schema {} is not registered", C::NAME)))?;
        Ok((type_id, &self.bindings[&type_id]))
    }

    /// The binding of a component type, if of the given schema.
    pub fn bound<C: ComponentSchema>(&self, type_id: u16) -> Option<&ComponentBound> {
        self.bindings.get(&type_id).filter(|bound| bound.is::<C>())
    }

}


